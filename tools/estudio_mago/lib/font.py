AC={'acute':["00010","00100"],'grave':["01000","00100"],'circ':["00100","01010"],'tilde':["01101","10110"]}
ACC={'Á':('A','acute'),'À':('A','grave'),'Â':('A','circ'),'Ã':('A','tilde'),'É':('E','acute'),'Ê':('E','circ'),
     'Í':('I','acute'),'Ó':('O','acute'),'Ô':('O','circ'),'Õ':('O','tilde'),'Ú':('U','acute')}
def glyph(ch):
    """returns rows (9 tall: 2 accent rows + 7) and cedilla flag"""
    ch=ch.upper()
    if ch=='Ç': return ["00000"]*3+G['C'],True
    if ch in ACC:
        base,mark=ACC[ch]; return AC[mark]+["00000"]+G[base],False
    rows=G.get(ch,G['?']); return ["0"*len(rows[0])]*3+rows,False
def text_width(s,scale=1): return sum((len(glyph(c)[0][0])+1)*scale for c in s)-scale
def draw_text(img,s,x,y,col,scale=1,outline=(10,6,18),shadow=None):
    """y is the top of capital letters; accents go 2*scale above. Outline drawn 1px (unscaled) around."""
    d=ImageDraw.Draw(img)
    def put(px,py,c):
        d.rectangle([px,py,px+scale-1,py+scale-1],fill=c)
    cells=[]
    cx=x
    for ch in s:
        rows,ced=glyph(ch)
        for j,r in enumerate(rows):
            for i,b in enumerate(r):
                if b=='1': cells.append((cx+i*scale,y+(j-3)*scale))
        if ced: cells.append((cx+2*scale,y+7*scale)); cells.append((cx+1*scale,y+8*scale))
        cx+=(len(rows[0])+1)*scale
    if shadow:
        for (px,py) in cells:
            d.rectangle([px-1,py+1,px+scale,py+scale+2],fill=shadow)
    if outline:
        for (px,py) in cells: d.rectangle([px-1,py-1,px+scale,py+scale],fill=outline)
    for (px,py) in cells: put(px,py,col)
def wrap(s,maxw,scale):
    words=s.split(' '); lines=[]; cur=''
    for w in words:
        t=(cur+' '+w).strip()
        if text_width(t,scale)<=maxw or not cur: cur=t
        else: lines.append(cur); cur=w
    if cur: lines.append(cur)
    return lines
